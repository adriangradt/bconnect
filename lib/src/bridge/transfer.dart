import 'dart:async';
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import '../raknet/binary.dart';

/// Bedrock game packet ids used for the login hand-off.
abstract final class BedrockPacketId {
  static const int login = 0x01;
  static const int playStatus = 0x02;
  static const int disconnect = 0x05;
  static const int resourcePackClientResponse = 0x08;
  static const int requestChunkRadius = 0x45;
  static const int chunkRadiusUpdate = 0x46;
  static const int setLocalPlayerAsInitialized = 0x71;
  static const int transfer = 0x55;
  static const int networkSettings = 0x8f;
  static const int requestNetworkSettings = 0xc1;
}

/// Protocol numbers where the wire format changed.
abstract final class BedrockProtocol {
  /// 1.19.30: client asks for network settings before Login.
  static const int networkSettings = 554;

  /// 1.20.60: every batch starts with a compression algorithm byte.
  static const int compressorInHeader = 649;

  /// 1.21.30: Transfer gained `reload_world`.
  static const int transferReloadWorld = 729;

  /// 1.26.40: Transfer gained an optional gatherings configuration, and
  /// ResourcePackClientResponse switched to a varint status without "none".
  static const int transferGatherings = 2168;
}

/// When the Transfer packet is sent. Minecraft ignores a Transfer that
/// arrives before the player is in a world, so the session walks the client
/// through a minimal, empty spawn first. Only [afterInitialized] works with
/// real clients (tested with Minecraft 26.3 on Windows); the others are kept
/// for experiments.
enum TransferStage { afterLogin, afterPacks, afterStartGame, afterInitialized }

/// Pre-serialised spawn packets for one protocol version, generated by
/// tool/spawn/gen_templates.js. Each entry is a complete game packet
/// (header varint included).
class SpawnTemplates {
  SpawnTemplates({
    required this.resourcePacksInfo,
    required this.resourcePackStack,
    required this.playStatusSpawn,
    required this.spawnSequence,
  });

  final Uint8List resourcePacksInfo;
  final Uint8List resourcePackStack;
  final Uint8List playStatusSpawn;

  /// Empty-world spawn: structure data, StartGame, registries, empty
  /// chunks, spawn status, movement attribute.
  final List<Uint8List> spawnSequence;
}

/// All spawn templates shipped with the app, keyed by protocol number.
class SpawnTemplateStore {
  SpawnTemplateStore(this._byProtocol) : _protocols = _byProtocol.keys.toList()..sort();

  /// Parses the gzipped JSON written by tool/spawn/gen_templates.js.
  factory SpawnTemplateStore.fromGzip(List<int> gz) {
    final json = jsonDecode(utf8.decode(gzip.decode(gz))) as Map<String, dynamic>;
    Uint8List hex(String s) =>
        Uint8List.fromList([for (var i = 0; i < s.length; i += 2) int.parse(s.substring(i, i + 2), radix: 16)]);
    return SpawnTemplateStore({
      for (final e in json.entries)
        int.parse(e.key): SpawnTemplates(
          resourcePacksInfo: hex(e.value['resource_packs_info'] as String),
          resourcePackStack: hex(e.value['resource_pack_stack'] as String),
          playStatusSpawn: hex(e.value['play_status_spawn'] as String),
          spawnSequence: [for (final h in e.value['spawn'] as List) hex(h as String)],
        ),
    });
  }

  final Map<int, SpawnTemplates> _byProtocol;
  final List<int> _protocols;

  List<int> get protocols => List.unmodifiable(_protocols);

  /// Exact match, else the closest older protocol. A client newer than all
  /// templates gets the newest one; packets rarely change between releases.
  SpawnTemplates? forProtocol(int protocol) {
    if (_protocols.isEmpty || protocol < _protocols.first) return null;
    final exact = _byProtocol[protocol];
    if (exact != null) return exact;
    return _byProtocol[_protocols.lastWhere((p) => p < protocol)];
  }
}

/// Splits a decompressed batch into game packets.
List<Uint8List> splitBatch(Uint8List batch) {
  final r = ByteReader(batch);
  final out = <Uint8List>[];
  while (!r.done) {
    out.add(Uint8List.fromList(r.bytes(r.varuint())));
  }
  return out;
}

Uint8List joinBatch(List<Uint8List> packets) {
  final w = ByteWriter();
  for (final p in packets) {
    w.varuint(p.length);
    w.bytes(p);
  }
  return w.take();
}

/// Handles one console from RakNet connect until it is sent to the real server.
///
/// This is what lets the phone step away after joining: the console logs in
/// to the bridge, the bridge answers with "login ok" and a Transfer packet,
/// and the console reconnects straight to [targetHost]:[targetPort]. From then
/// on the game traffic no longer passes through the phone.
///
/// No encryption is negotiated (the bridge never sends a server-to-client
/// handshake), so packets stay readable for the short login phase.
class BedrockTransferSession {
  BedrockTransferSession({
    required this.targetHost,
    required this.targetPort,
    required this.sendBatch,
    required this.onTransferred,
    this.onLog,
    this.stage = TransferStage.afterInitialized,
    this.templatesFor,
  });

  final TransferStage stage;

  /// Looks up spawn packets for a protocol; null if none are known.
  final SpawnTemplates? Function(int protocol)? templatesFor;
  SpawnTemplates? _spawn;

  final String targetHost;
  final int targetPort;

  /// Sends a game batch payload (without the 0xFE byte).
  final void Function(Uint8List payload) sendBatch;
  final void Function(int protocol) onTransferred;
  final void Function(String message)? onLog;

  static final _deflate = ZLibCodec(raw: true, level: 6);

  int? protocol;
  bool _compression = false;
  bool transferred = false;

  void handleBatch(Uint8List payload) {
    if (transferred || payload.isEmpty) return;
    final List<Uint8List> packets;
    try {
      packets = splitBatch(_decompress(payload));
    } on Object catch (e) {
      onLog?.call('Unreadable packet from console: $e');
      return;
    }
    for (final p in packets) {
      final r = ByteReader(p);
      final id = r.varuint() & 0x3ff;
      switch (id) {
        case BedrockPacketId.requestNetworkSettings:
          protocol = r.i32be();
          _send([_networkSettings()]);
          _compression = true;
        case BedrockPacketId.login:
          protocol ??= r.i32be();
          _spawn = templatesFor?.call(protocol!);
          onLog?.call('login, protocol $protocol, spawn templates ${_spawn != null}');
          if (stage == TransferStage.afterLogin || _spawn == null) {
            _transfer();
            return;
          }
          _send([_playStatus(0), _spawn!.resourcePacksInfo]);
        case BedrockPacketId.resourcePackClientResponse:
          final status = _packStatus(r);
          onLog?.call('resource pack response $status');
          if (_spawn == null) break;
          if (status == _PackStatus.haveAll) {
            _send([_spawn!.resourcePackStack]);
          } else if (status == _PackStatus.completed) {
            if (stage == TransferStage.afterPacks) {
              _transfer();
              return;
            }
            _send(_spawn!.spawnSequence);
            // Fallback in case the client never reports itself initialised.
            // A Transfer before that is ignored, so wait generously.
            Timer(const Duration(seconds: 15), _transfer);
            if (stage == TransferStage.afterStartGame) {
              _transfer();
              return;
            }
          }
        case BedrockPacketId.requestChunkRadius:
          final radius = _readZigzag(r);
          onLog?.call('chunk radius $radius requested');
          final w = ByteWriter()
            ..varuint(BedrockPacketId.chunkRadiusUpdate)
            ..varuint((radius << 1) ^ (radius >> 31));
          _send([w.take(), if (_spawn != null) _spawn!.playStatusSpawn]);
        case BedrockPacketId.setLocalPlayerAsInitialized:
          onLog?.call('player initialized');
          _transfer();
          return;
        default:
          onLog?.call('packet 0x${id.toRadixString(16)} (${p.length} bytes)');
      }
    }
  }

  Uint8List _decompress(Uint8List p) {
    if (_compression && (protocol ?? 0) >= BedrockProtocol.compressorInHeader) {
      final rest = Uint8List.sublistView(p, 1);
      return switch (p[0]) {
        0x00 => Uint8List.fromList(_deflate.decode(rest)),
        0xff => rest,
        _ => throw PacketFormatException('compression ${p[0]} not supported'),
      };
    }
    if (_compression || protocol == null) {
      // Before 1.20.60, or before 1.19.30 (no network settings at all),
      // batches are deflated. The very first RequestNetworkSettings is not.
      try {
        return Uint8List.fromList(_deflate.decode(p));
      } on Object {
        return p;
      }
    }
    return p;
  }

  void _send(List<Uint8List> packets) {
    final batch = joinBatch(packets);
    if (!_compression) {
      sendBatch(batch);
    } else if ((protocol ?? 0) >= BedrockProtocol.compressorInHeader) {
      // Large batches (the spawn) are deflated, small ones go as is (0xFF).
      sendBatch(batch.length > 512
          ? Uint8List.fromList([0x00, ..._deflate.encode(batch)])
          : Uint8List.fromList([0xff, ...batch]));
    } else {
      sendBatch(Uint8List.fromList(_deflate.encode(batch)));
    }
  }

  int _readZigzag(ByteReader r) {
    final v = r.varuint();
    return (v >> 1) ^ -(v & 1);
  }

  _PackStatus _packStatus(ByteReader r) {
    if ((protocol ?? 0) >= BedrockProtocol.transferGatherings) {
      return switch (r.varuint()) {
        2 => _PackStatus.haveAll,
        3 => _PackStatus.completed,
        _ => _PackStatus.other,
      };
    }
    // Older clients: u8 with 0 = none, 3 = have all packs, 4 = completed.
    return switch (r.u8()) {
      3 => _PackStatus.haveAll,
      4 => _PackStatus.completed,
      _ => _PackStatus.other,
    };
  }

  Uint8List _playStatus(int status) {
    final w = ByteWriter()
      ..varuint(BedrockPacketId.playStatus)
      ..i32be(status);
    return w.take();
  }

  Uint8List _networkSettings() {
    final w = ByteWriter()
      ..varuint(BedrockPacketId.networkSettings)
      ..u16le(1) // compression threshold
      ..u16le(0) // deflate
      ..boolean(false) // client throttle
      ..u8(0)
      ..f32le(0);
    return w.take();
  }

  void _transfer() {
    if (transferred) return;
    final p = protocol ?? 0;
    final transfer = ByteWriter()
      ..varuint(BedrockPacketId.transfer)
      ..string(targetHost)
      ..u16le(targetPort);
    // reload_world false, as Cloudburst (Geyser, BedrockConnect) sends it.
    // With true, Minecraft 26.x stays in the bridge's empty world.
    if (p >= BedrockProtocol.transferReloadWorld) transfer.boolean(false);
    if (p >= BedrockProtocol.transferGatherings) transfer.boolean(false); // no gatherings info
    // Without the spawn walk-through, login success goes in the same batch.
    _send([if (_spawn == null || stage == TransferStage.afterLogin) _playStatus(0), transfer.take()]);
    transferred = true;
    onTransferred(p);
  }
}

enum _PackStatus { haveAll, completed, other }
